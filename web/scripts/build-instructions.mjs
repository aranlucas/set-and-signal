import { mkdir, readdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";
import {
  instructionShard,
  INSTRUCTION_SHARD_COUNT,
} from "../src/domain/exercises/instruction-shard.ts";

const projectRoot = dirname(import.meta.dirname);
const sourceCatalogPath = join(projectRoot, "catalog", "exercises.ts");
const sourceLocalesDirectory = join(projectRoot, "catalog", "instructions");
const generatedCatalogPath = join(projectRoot, "src", "generated", "exercises-data.ts");
const generatedDirectory = join(projectRoot, "public", "instructions");
const temporaryDirectory = join(projectRoot, "public", "instructions.next");

const sourceCatalogModule = await import(pathToFileURL(sourceCatalogPath).href);
const sourceCatalog = sourceCatalogModule.EXDB;
if (!Array.isArray(sourceCatalog) || sourceCatalog.length === 0) {
  throw new Error("Exercise source catalogue is empty or invalid");
}

const ids = sourceCatalog.map((exercise) => exercise.id);
const uniqueIds = new Set(ids);
if (uniqueIds.size !== ids.length)
  throw new Error("Exercise source catalogue contains duplicate ids");

const englishInstructions = Object.fromEntries(
  sourceCatalog.map((exercise) => {
    if (!Array.isArray(exercise.st) || exercise.st.length === 0) {
      throw new Error(`Exercise ${exercise.id} has no English instructions`);
    }
    return [exercise.id, exercise.st];
  }),
);

const compactCatalog = sourceCatalog.map(({ st: _instructions, ...exercise }) => exercise);
const catalogSource = `// Generated by scripts/build-instructions.mjs — do not edit.\nimport type { Exercise } from "@/shared/lib/types.js";\n\nexport const EXDB: Exercise[] = ${JSON.stringify(compactCatalog, null, 2)};\n`;

const currentCatalog = await readFile(generatedCatalogPath, "utf8").catch(() => "");
if (currentCatalog !== catalogSource) await writeFile(generatedCatalogPath, catalogSource);

const localeFiles = (await readdir(sourceLocalesDirectory))
  .filter((filename) => filename.endsWith(".ts"))
  .toSorted();
const instructionSets = new Map([["en", englishInstructions]]);

for (const filename of localeFiles) {
  const language = filename.slice(0, -3);
  const module = await import(pathToFileURL(join(sourceLocalesDirectory, filename)).href);
  const instructions = module.default;
  const localeIds = Object.keys(instructions);
  const missing = ids.filter((id) => !Object.hasOwn(instructions, id));
  const unknown = localeIds.filter((id) => !uniqueIds.has(id));
  if (missing.length > 0 || unknown.length > 0) {
    throw new Error(
      `${language} instructions mismatch: ${missing.length} missing, ${unknown.length} unknown`,
    );
  }
  instructionSets.set(language, instructions);
}

await rm(temporaryDirectory, { recursive: true, force: true });
await mkdir(temporaryDirectory, { recursive: true });

for (const [language, instructions] of instructionSets) {
  const languageDirectory = join(temporaryDirectory, language);
  await mkdir(languageDirectory, { recursive: true });
  const shards = Array.from({ length: INSTRUCTION_SHARD_COUNT }, () => ({}));
  for (const id of ids) {
    const shard = Number(instructionShard(id));
    shards[shard][id] = instructions[id];
  }
  await Promise.all(
    shards.map((entries, index) => {
      const shard = String(index).padStart(2, "0");
      return writeFile(
        join(languageDirectory, `instructions-${language}-${shard}.json`),
        `${JSON.stringify(entries)}\n`,
      );
    }),
  );
}

await rm(generatedDirectory, { recursive: true, force: true });
await rename(temporaryDirectory, generatedDirectory);

console.log(
  `Generated ${compactCatalog.length} compact exercises and ${instructionSets.size * INSTRUCTION_SHARD_COUNT} instruction shards.`,
);
